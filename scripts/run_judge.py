# ============================================================================
# An AI judge, checked against NIST's answer keys (src/controlfinder/judge.py).
#
# Run:   Ollama with granite4:3b and qwen3:8b
#        python scripts/run_judge.py            (about 20 minutes on this Mac;
#                                                every reply is kept, so a rerun skips it)
#        python scripts/run_judge.py --report   (no model: the report from the kept replies)
# Judged: step 6's chosen setup's answers to the test questions (130, kept in
# results/answers_all.json). Both models judge every one with the same prompt,
# written before any judge ran. Nothing is chosen, so no dev questions are
# needed. qwen3:8b wrote these answers, so it judges its own work; granite4:3b
# didn't.
# Writes results/judge.json, results/judge_answers.json (every reply), and
# docs/results-judge.md.
# ============================================================================
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from controlfinder import answer, judge  # noqa: E402
from controlfinder.answer_key import load_csf_questions, load_out_of_scope, load_plain_questions, load_questions  # noqa: E402
from controlfinder.catalog import active_controls  # noqa: E402

JUDGES = ["granite4:3b", "qwen3:8b"]
SETS = {"csf2": ("CSF 2.0", load_csf_questions), "sp800_171": ("SP 800-171 Rev 3", load_questions),
        "plain_english": ("Plain-English", load_plain_questions), "out_of_scope": ("Out of scope", load_out_of_scope)}
KEPT = ROOT / "results" / "judge_answers.json"
CHOSEN = f"{answer.CHOSEN['model']}, prompt {answer.CHOSEN['version']}, top {answer.CHOSEN['shown']}"


def judged_answers():
    kept = json.loads((ROOT / "results" / "answers_all.json").read_text(encoding="utf-8"))
    return [r for r in kept if r["config"] == CHOSEN and r["split"] == "test"]


def score(rows, replies, questions, by_id):
    by_reply = {(r["judge"], r["set"], r["id"]): r for r in replies}
    out = {}
    for model in JUDGES:
        if any((model, r["set"], r["id"]) not in by_reply for r in rows):
            continue
        pairs = {key: [] for key in SETS}
        disagree = []
        for r in rows:
            shown = [by_id[c] for c in r["shown"]]
            covered, _, cited = answer.parse(r["raw"], shown) or (False, "", [])
            key_says = judge.truth(r["set"], questions[(r["set"], r["id"])], covered, cited)
            judge_says = judge.verdict(by_reply[(model, r["set"], r["id"])]["raw"])
            pairs[r["set"]].append((key_says, judge_says))
            if judge_says is not None and judge_says != key_says:
                disagree.append({"set": r["set"], "id": r["id"], "key_says_right": key_says, "covered": covered,
                                 "cited": [by_id[c].label for c in cited]})
        seconds = [by_reply[(model, r["set"], r["id"])]["seconds"] for r in rows]
        out[model] = {"all": judge.agreement([p for v in pairs.values() for p in v]),
                      "by_set": {key: judge.agreement(v) for key, v in pairs.items()},
                      "median_seconds": round(statistics.median(seconds), 2), "disagreements": disagree}
    return out


def pct(x):
    return "n/a" if x is None else f"{x * 100:.1f}%"


def table(rows):
    lines = ["| Judge | Answers | The key says wrong | Agreement | Cohen's kappa | Wrong answers caught | "
             "Flags that are wrong answers | Right answers flagged | Invalid replies |", "|---|---|---|---|---|---|---|---|---|"]
    for name, a in rows:
        lines.append(f"| {name} | {a['answers']} | {a['key_says_wrong']} | {pct(a['agreement'])} | {a['kappa']:.3f} | "
                     f"{pct(a['wrong_answers_caught'])} | {pct(a['flags_that_are_wrong_answers'])} | "
                     f"{a['right_answers_flagged']} | {a['invalid']} |")
    return "\n".join(lines)


def render(results):
    lines = ["# Results: an AI judge, checked against NIST's answer keys", "",
             "Generated by `scripts/run_judge.py`. Don't edit by hand.", "",
             f"Step 6's chosen setup ({CHOSEN}) answered the {results['answers']} test questions. A local model then "
             "judged each answer people were shown: right when the controls it cites address the question, or, when it "
             "says the question isn't covered, when none of the controls found do (`src/controlfinder/judge.py`). The "
             "answer keys decide the same thing: right when the answer cites a control NIST links to the question (an "
             "anchor, for a plain-English one), or says \"not covered\" to a question SP 800-53 doesn't answer. One "
             "prompt, written before any judge ran, and nothing tuned. qwen3:8b wrote these answers, so it judges its "
             "own work.", "", "## Every test answer", ""]
    lines.append(table([(m, r["all"]) for m, r in results["judges"].items()]))
    for key, (label, _) in SETS.items():
        lines += ["", f"### {label}", "", table([(m, r["by_set"][key]) for m, r in results["judges"].items()])]
    lines += ["", "Agreement and kappa leave out invalid replies. Kappa is agreement beyond what chance would give "
                  "(0 is chance, 1 is complete agreement). \"Wrong answers caught\" is the share of answers the key "
                  "calls wrong that the judge also calls wrong; \"flags that are wrong answers\" is the share of the "
                  "judge's \"wrong\" verdicts the key agrees with.", ""]
    return "\n".join(lines)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    by_id = {c.id: c for c in active_controls()}
    questions = {(key, q.id): q for key, (_, load) in SETS.items() for q in load()}
    rows = judged_answers()
    replies = json.loads(KEPT.read_text(encoding="utf-8")) if KEPT.exists() else []
    if "--report" not in argv:
        done = {(r["judge"], r["set"], r["id"]) for r in replies}
        for model in JUDGES:
            for n, r in enumerate(rows, 1):
                if (model, r["set"], r["id"]) in done:
                    continue
                shown = [by_id[c] for c in r["shown"]]
                covered, text, cited = answer.parse(r["raw"], shown) or (False, "", [])
                reply = judge.ask(questions[(r["set"], r["id"])].text, shown, covered, text, cited, model)
                replies.append({"judge": model, "set": r["set"], "id": r["id"], **reply})
                KEPT.write_text(json.dumps(replies, indent=1) + "\n", encoding="utf-8")
                print(f"  {model}: {n}/{len(rows)} ({reply['seconds']:.1f} s)", flush=True)
    results = {"answers": len(rows), "judged": CHOSEN, "judges": score(rows, replies, questions, by_id)}
    (ROOT / "results" / "judge.json").write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
    doc = render(results)
    (ROOT / "docs" / "results-judge.md").write_text(doc, encoding="utf-8")
    print(doc)


if __name__ == "__main__":
    main()
