# ============================================================================
# Following NIST's links between controls (src/controlfinder/related.py).
#
# Run:   python scripts/run_related.py   (no model or database: the committed vector results)
#   1. The weighted hybrid search of step 4, recomputed: keyword (BM25) and the
#      committed vector top 100, fused with the vector list counting 3 times.
#   2. 12 settings, tried on CSF 2.0 dev questions only: links one way or both
#      ways; the top 5 or 10 results as seeds; a weight of 0.25, 0.5, or 1.
#      The best by MRR (then recall@10, then the smaller weight, then fewer
#      seeds, then one way) runs once on both keys' test questions.
#   3. Writes results/related.json and docs/results-related.md.
# Every score uses the top 10, the same as steps 1 to 4.
# ============================================================================
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from controlfinder.answer_key import load_csf_questions, load_questions  # noqa: E402
from controlfinder.bm25 import BM25  # noqa: E402
from controlfinder.catalog import active_controls  # noqa: E402
from controlfinder.metrics import summarize  # noqa: E402
from controlfinder.related import expand, fusion_scores, related_links  # noqa: E402

VECTOR_TEXT = "title + statement + guidance"  # step 3's choice
VECTOR_WEIGHT = 3.0  # step 4's choice
SETTINGS = [{"both_ways": b, "seeds": s, "weight": w} for b in (False, True) for s in (5, 10) for w in (0.25, 0.5, 1.0)]
KEYS = {"csf2": ("CSF 2.0", load_csf_questions), "sp800_171": ("SP 800-171 Rev 3", load_questions)}
METRICS = ["mrr", "hit@1", "hit@5", "hit@10", "recall@10", "precision@5"]


def name(setting):
    return (f"{'both ways' if setting['both_ways'] else 'one way'}, {setting['seeds']} seeds, "
            f"weight {setting['weight']:g}")


def score(rankings, questions, split):
    return summarize([(rankings[q.id][:10], q.expected) for q in questions if q.split == split])


def table(rows):
    lines = ["| Method | Questions | " + " | ".join(METRICS) + " |", "|---|---|" + "---|" * len(METRICS)]
    for label, m in rows:
        lines.append(f"| {label} | {m['questions']} | " + " | ".join(f"{m[x]:.3f}" for x in METRICS) + " |")
    return "\n".join(lines)


def main():
    controls = active_controls()
    ids = [c.id for c in controls]
    keys = {key: load() for key, (_, load) in KEYS.items()}
    vector = json.loads((ROOT / "results" / "vector_top100.json").read_text())[VECTOR_TEXT]
    bm25 = BM25([f"{c.title}. {c.statement} {c.guidance}" for c in controls])
    fused = {}
    for key, questions in keys.items():
        for q in questions:
            keyword = [controls[i].id for i, _ in bm25.search(q.text, 100)]
            fused[key, q.id] = fusion_scores([keyword, vector[key][q.id]], k=60, depth=100,
                                             weights=[1.0, VECTOR_WEIGHT])
    links = {both: related_links(ids, both_ways=both) for both in (False, True)}

    def rankings(key, setting):
        if setting is None:
            return {q.id: expand(*fused[key, q.id], links[False], 0, 0.0) for q in keys[key]}
        return {q.id: expand(*fused[key, q.id], links[setting["both_ways"]], setting["seeds"], setting["weight"])
                for q in keys[key]}

    csf = keys["csf2"]
    dev = {name(s): score(rankings("csf2", s), csf, "dev") for s in SETTINGS}
    base_dev = score(rankings("csf2", None), csf, "dev")
    best = max(SETTINGS, key=lambda s: (dev[name(s)]["mrr"], dev[name(s)]["recall@10"], -s["weight"], -s["seeds"],
                                        -s["both_ways"]))
    test = {key: {"hybrid, vector weight 3 (step 4)": score(rankings(key, None), keys[key], "test"),
                  f"with links: {name(best)}": score(rankings(key, best), keys[key], "test")} for key in keys}
    published = json.loads((ROOT / "results" / "rerank.json").read_text())["test"]
    counted = {"one_way": sum(len(v) for v in links[False].values()),
               "both_ways": sum(len(v) for v in links[True].values()) // 2}
    results = {"settings": SETTINGS, "links_between_active_controls": counted,
               "dev_csf2": {"hybrid, vector weight 3 (step 4)": base_dev, **dev}, "chosen": best, "test": test}
    (ROOT / "results" / "related.json").write_text(json.dumps(results, indent=2) + "\n")

    rerank_name = next(n for n in published["csf2"] if n.startswith("reranked"))
    lines = ["# Results: following NIST's links between controls", "",
             "Generated by `scripts/run_related.py`. Don't edit by hand.", "",
             f"NIST's catalog links each control to related ones: {counted['one_way']:,} links between the "
             f"{len(ids):,} active controls and enhancements. The weighted hybrid search's top results lend part of "
             "their score to the controls they link to (`src/controlfinder/related.py`), and the list is sorted again. "
             "No model or database is needed: the vector results are the committed ones from step 3.", "",
             "## Chosen on CSF 2.0 dev questions", "",
             table([("hybrid, vector weight 3 (step 4)", base_dev)] + [(name(s), dev[name(s)]) for s in SETTINGS]), "",
             f"Chosen by MRR (then recall@10, then the smaller weight, fewer seeds, one way): **{name(best)}**.", "",
             "## Test questions, run once", ""]
    for key, (label, _) in KEYS.items():
        rows = list(test[key].items()) + [(f"{rerank_name} (step 4, for comparison)", published[key][rerank_name])]
        lines += [f"### {label}", "", table(rows), ""]
    (ROOT / "docs" / "results-related.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
