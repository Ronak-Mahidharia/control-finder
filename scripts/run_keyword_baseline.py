# ============================================================================
# The keyword baseline: BM25 search over the SP 800-53 catalog, scored on both
# answer keys (SP 800-171 Rev 3, and the harder CSF 2.0 outcomes).
#
# Run:   python scripts/run_keyword_baseline.py
#   1. Builds one search index per way of writing a control (title and
#      statement; plus guidance; plus assessment objectives).
#   2. For each answer key, scores each one on the dev questions only, and
#      picks the best by MRR.
#   3. Scores that one choice on the key's test questions, once.
#   4. Writes every question's top 10 to results/keyword_baseline.json (SP 800-171)
#      and results/keyword_baseline_csf2.json (CSF 2.0), and the tables to docs/results.md.
# Everything is deterministic: the same data gives the same numbers.
# ============================================================================
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from controlfinder.answer_key import load_csf_questions, load_questions  # noqa: E402
from controlfinder.bm25 import BM25  # noqa: E402
from controlfinder.catalog import active_controls  # noqa: E402
from controlfinder.metrics import summarize  # noqa: E402

OSCAL_COMMIT = "78650f02ad9321bb7b817846f8fbd4f2bcd620de"
VARIANTS = {
    "title + statement": lambda c: f"{c.title}. {c.statement}",
    "title + statement + guidance": lambda c: f"{c.title}. {c.statement} {c.guidance}",
    "title + statement + guidance + objectives": lambda c: f"{c.title}. {c.statement} {c.guidance} {' '.join(c.objectives)}",
}
METRICS = ["mrr", "hit@1", "recall@5", "recall@10", "hit@10", "precision@5"]


def rank_all(index, controls, questions, k=10):
    return {q.id: [controls[i].id for i, _ in index.search(q.text, k)] for q in questions}


def evaluate(rankings, questions):
    return summarize([(rankings[q.id], q.expected) for q in questions])


def table(rows):
    lines = ["| Search text | Questions | " + " | ".join(METRICS) + " |", "|---|---|" + "---|" * len(METRICS)]
    for name, m in rows:
        lines.append(f"| {name} | {m['questions']} | " + " | ".join(f"{m[x]:.3f}" for x in METRICS) + " |")
    return "\n".join(lines)


def run_key(controls, indexes, questions):
    """Pick the search text on dev, score it on test once, and keep every question's top 10."""
    dev = [q for q in questions if q.split == "dev"]
    test = [q for q in questions if q.split == "test"]
    dev_scores = {name: evaluate(rank_all(index, controls, dev), dev) for name, index in indexes.items()}
    chosen = max(VARIANTS, key=lambda name: (dev_scores[name]["mrr"], dev_scores[name]["recall@10"]))
    chosen_rankings = rank_all(indexes[chosen], controls, questions)
    test_score = evaluate(chosen_rankings, test)
    best_mrr = [n for n in VARIANTS if dev_scores[n]["mrr"] == dev_scores[chosen]["mrr"]]
    why = ("It has the highest MRR." if len(best_mrr) == 1 else
           f"{len(best_mrr)} versions tie on MRR ({dev_scores[chosen]['mrr']:.3f}), so the tie goes to the highest recall@10, "
           "and then to the shorter text.")
    results = {
        "data": {"oscal_commit": OSCAL_COMMIT, "documents": len(controls), "questions": len(questions),
                 "dev": len(dev), "test": len(test)},
        "settings": {"k1": 1.5, "b": 0.75},
        "dev": dev_scores,
        "chosen": chosen,
        "test": test_score,
        "rankings": {q.id: {"split": q.split, "title": q.title, "expected": sorted(q.expected),
                            "top10": chosen_rankings[q.id]} for q in questions},
    }
    return results, why


def main():
    controls = active_controls()
    indexes = {name: BM25([text(c) for c in controls]) for name, text in VARIANTS.items()}
    sp171, why171 = run_key(controls, indexes, load_questions())
    csf, why_csf = run_key(controls, indexes, load_csf_questions())
    (ROOT / "results").mkdir(exist_ok=True)
    for name, results in (("keyword_baseline.json", sp171), ("keyword_baseline_csf2.json", csf)):
        (ROOT / "results" / name).write_text(json.dumps(results, indent=1) + "\n", encoding="utf-8")
    refs171 = sum(len(r["expected"]) for r in sp171["rankings"].values())
    refs_csf = sum(len(r["expected"]) for r in csf["rankings"].values())

    doc = f"""# Results

Generated by `scripts/run_keyword_baseline.py` from NIST's OSCAL files at commit `{OSCAL_COMMIT[:12]}`. Every question's top 10 is in `results/keyword_baseline.json` (SP 800-171) and `results/keyword_baseline_csf2.json` (CSF 2.0).

Both keys search the same {len(controls)} active SP 800-53 Rev 5.2.0 controls and enhancements, split their questions into dev and test by a hash of the question's ID, and choose settings on dev only.

## Answer key 1: SP 800-171 Rev 3 (easy for keywords)
- **Questions:** {sp171['data']['questions']} active NIST SP 800-171 Rev 3 requirements ({sp171['data']['dev']} dev, {sp171['data']['test']} test). Each question is a requirement's statement; its title is left out, because it often repeats a control's title.
- **Right answers:** the SP 800-53 controls NIST lists as each requirement's sources ({refs171} in all).

### Keyword search (BM25), dev questions
{table(list(sp171['dev'].items()))}

**Chosen on dev:** {sp171['chosen']}. {why171}

### Keyword search (BM25), test questions
{table([(sp171['chosen'], sp171['test'])])}

## Answer key 2: CSF 2.0 outcomes (the hard one)
- **Questions:** {csf['data']['questions']} outcomes (subcategories) of NIST's Cybersecurity Framework 2.0 ({csf['data']['dev']} dev, {csf['data']['test']} test), for example "Vulnerabilities in assets are identified, validated, and recorded".
- **Right answers:** the SP 800-53 controls NIST's CSF 2.0 Reference Tool lists as each outcome's informative references ({refs_csf} in all, 1 to {max(len(r['expected']) for r in csf['rankings'].values())} per outcome). Built by `scripts/build_csf_answer_key.py` into `answer_keys/csf2_sp800_53.json`.

### Keyword search (BM25), dev questions
{table(list(csf['dev'].items()))}

**Chosen on dev:** {csf['chosen']}. {why_csf}

### Keyword search (BM25), test questions
{table([(csf['chosen'], csf['test'])])}

## Reading these numbers
- **MRR:** 1 divided by the rank of the first right control, averaged. 1.000 means a right control always came first.
- **hit@k:** how often a right control is in the top k. **recall@k:** the share of the right controls found in the top k.
- **Key 1 is easy for keyword search.** NIST wrote each SP 800-171 requirement by adapting the wording of its source controls, so question and answer share many words.
- **Key 2 is hard for it.** CSF outcomes describe results in different words from the controls, so keyword search finds a right control first only about 1 time in 5. This is the key the next steps (vector search, hybrid search, reranking) are measured on.
- **Recall@10 has a ceiling on key 2.** An outcome with more than 10 right controls can't have all of them in a top 10.
"""
    (ROOT / "docs" / "results.md").write_text(doc, encoding="utf-8")
    for label, r in (("SP 800-171", sp171), ("CSF 2.0", csf)):
        print(f"== {label}\n{table(list(r['dev'].items()))}\nchosen on dev: {r['chosen']}\n{table([(r['chosen'], r['test'])])}\n")


if __name__ == "__main__":
    main()
