# ============================================================================
# The keyword baseline: BM25 search over the SP 800-53 catalog, scored on the
# SP 800-171 Rev 3 answer key.
#
# Run:   python scripts/run_keyword_baseline.py
#   1. Builds one search index per way of writing a control (title and
#      statement; plus guidance; plus assessment objectives).
#   2. Scores each one on the dev questions only, and picks the best by MRR.
#   3. Scores that one choice on the test questions, once.
#   4. Writes every question's top 10 to results/keyword_baseline.json and the
#      tables to docs/results.md.
# Everything is deterministic: the same data gives the same numbers.
# ============================================================================
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from controlfinder.answer_key import load_questions  # noqa: E402
from controlfinder.bm25 import BM25  # noqa: E402
from controlfinder.catalog import active_controls  # noqa: E402
from controlfinder.metrics import summarize  # noqa: E402

OSCAL_COMMIT = "78650f02ad9321bb7b817846f8fbd4f2bcd620de"
VARIANTS = {
    "title + statement": lambda c: f"{c.title}. {c.statement}",
    "title + statement + guidance": lambda c: f"{c.title}. {c.statement} {c.guidance}",
    "title + statement + guidance + objectives": lambda c: f"{c.title}. {c.statement} {c.guidance} {' '.join(c.objectives)}",
}
METRICS = ["mrr", "hit@1", "recall@5", "recall@10", "hit@10", "precision@5"]


def rank_all(index, controls, questions, k=10):
    return {q.id: [controls[i].id for i, _ in index.search(q.text, k)] for q in questions}


def evaluate(rankings, questions):
    return summarize([(rankings[q.id], q.expected) for q in questions])


def table(rows):
    lines = ["| Search text | Questions | " + " | ".join(METRICS) + " |", "|---|---|" + "---|" * len(METRICS)]
    for name, m in rows:
        lines.append(f"| {name} | {m['questions']} | " + " | ".join(f"{m[x]:.3f}" for x in METRICS) + " |")
    return "\n".join(lines)


def main():
    controls = active_controls()
    questions = load_questions()
    dev = [q for q in questions if q.split == "dev"]
    test = [q for q in questions if q.split == "test"]

    indexes = {name: BM25([text(c) for c in controls]) for name, text in VARIANTS.items()}
    dev_scores = {name: evaluate(rank_all(index, controls, dev), dev) for name, index in indexes.items()}
    chosen = max(VARIANTS, key=lambda name: (dev_scores[name]["mrr"], dev_scores[name]["recall@10"]))
    chosen_rankings = rank_all(indexes[chosen], controls, questions)
    test_score = evaluate(chosen_rankings, test)
    best_mrr = [n for n in VARIANTS if dev_scores[n]["mrr"] == dev_scores[chosen]["mrr"]]
    why = ("It has the highest MRR." if len(best_mrr) == 1 else
           f"{len(best_mrr)} versions tie on MRR ({dev_scores[chosen]['mrr']:.3f}), so the tie goes to the highest recall@10, "
           "and then to the shorter text.")

    results = {
        "data": {"oscal_commit": OSCAL_COMMIT, "documents": len(controls), "questions": len(questions),
                 "dev": len(dev), "test": len(test)},
        "settings": {"k1": 1.5, "b": 0.75},
        "dev": dev_scores,
        "chosen": chosen,
        "test": test_score,
        "rankings": {q.id: {"split": q.split, "title": q.title, "expected": sorted(q.expected),
                            "top10": chosen_rankings[q.id]} for q in questions},
    }
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "keyword_baseline.json").write_text(json.dumps(results, indent=1) + "\n", encoding="utf-8")

    doc = f"""# Results

Generated by `scripts/run_keyword_baseline.py` from NIST's OSCAL files at commit `{OSCAL_COMMIT[:12]}`. Every question's top 10 is in `results/keyword_baseline.json`.

## The answer key
- **Questions:** {len(questions)} active NIST SP 800-171 Rev 3 requirements. Each question is a requirement's statement; its title is left out, because it often repeats a control's title.
- **Right answers:** the SP 800-53 controls NIST lists as each requirement's sources ({sum(len(q.expected) for q in questions)} in all).
- **Searched:** {len(controls)} active SP 800-53 Rev 5.2.0 controls and enhancements.
- **Split:** {len(dev)} dev and {len(test)} test questions, by a hash of the requirement number. Settings are chosen on dev only.

## Keyword search (BM25), dev questions
{table(list(dev_scores.items()))}

**Chosen on dev:** {chosen}. {why}

## Keyword search (BM25), test questions
{table([(chosen, test_score)])}

## Reading these numbers
- **MRR:** 1 divided by the rank of the first right control, averaged. 1.000 means a right control always came first.
- **hit@1:** how often the first result is right. **recall@k:** the share of the right controls found in the top k.
- **This answer key is easy for keyword search.** NIST wrote each SP 800-171 requirement by adapting the wording of its source controls, so the question and the right answer share many words. Plain-English questions will be harder, so these numbers are an upper bound for keyword search, not a measure of how it handles real users' questions.
"""
    (ROOT / "docs" / "results.md").write_text(doc, encoding="utf-8")
    print(table(list(dev_scores.items())))
    print(f"\nchosen on dev: {chosen}\n")
    print(table([(chosen, test_score)]))


if __name__ == "__main__":
    main()
